def calculate_lal_kitab_data(planets_data: List[Dict], lagna_sign: int, birth_date: str) -> Dict[str, Any]:
    """
    Compute Lal Kitab planetary status, 35-year dasha cycle, and house readings.
    """
    by_name = {p["name"]: p for p in planets_data if isinstance(p, dict) and p.get("name")}
    
    # 1. Lal Kitab Planetary Status Table
    planet_status_rows = []
    planets_order = ["Sun", "Moon", "Mars", "Mercury", "Jupiter", "Venus", "Saturn", "Rahu", "Ketu"]
    
    # Sign names in Nepali
    sign_names_ne = ["", "मेष", "वृष", "मिथुन", "कर्कट", "सिंह", "कन्या", "तुला", "वृश्चिक", "धनु", "मकर", "कुम्भ", "मीन"]
    
    for name in planets_order:
        p = by_name.get(name, {})
        house = p.get("house", 1)
        sign_num = p.get("sign_number", 1)
        sign_name = sign_names_ne[sign_num] if 1 <= sign_num <= 12 else ""
        
        # Lal Kitab Sleeping (Soya) vs Awake (Jaga) rules
        # If natural house of planet has no aspects or house is empty
        is_soya = house in [2, 3, 4, 5, 7, 8, 9, 10, 11] if name in ["Moon", "Mars", "Mercury", "Jupiter", "Venus", "Saturn"] else False
        soya_text = "हो" if is_soya else "होइन"
        
        # Kismat Jagane Wala Graha
        kismat_text = "हो" if (name == "Mars" and house == 1) or (name == "Sun" and house == 10) or (name == "Jupiter" and house == 2) else "होइन"
        
        # Nek (Benefic) vs Manda (Malefic) disposition in Lal Kitab
        is_nek = house in [1, 2, 5, 9, 10, 11] and not p.get("is_combust") and not (name in ["Rahu", "Ketu"] and house in [4, 8, 12])
        if name == "Mars" and house == 1:
            is_nek = True
        elif name == "Jupiter" and house == 2:
            is_nek = True
        elif name == "Sun" and house == 10:
            is_nek = True
        else:
            is_nek = is_nek and (name in ["Jupiter", "Sun", "Mars", "Moon"])
            
        nek_manda = "नेक / शुभ" if is_nek else "मन्दा / अशुभ"
        
        # Readings and upayas
        pred_dict = LAL_KITAB_PREDICTIONS.get(name, {}).get(house, {})
        if not pred_dict:
            # General fallback reading based on house
            pred_dict = {
                "phal": f"{PLANET_NE.get(name, name)} {house}औं भावमा रहँदा मिश्रित फल मिल्नेछ। कर्म अनुसार फल प्राप्त हुनेछ।",
                "upayas": ["कुलदेवताको पूजा गर्नुहोस्।", "सदाचारको पालना गर्नुहोस्।"]
            }
        
        planet_status_rows.append({
            "name": name,
            "name_ne": PLANET_NE.get(name, name),
            "sign_number": sign_num,
            "sign_name": sign_name,
            "house": house,
            "soya": soya_text,
            "kismat_jagane": kismat_text,
            "nek_manda": nek_manda,
            "is_nek": is_nek,
            "phal": pred_dict.get("phal", ""),
            "upayas": pred_dict.get("upayas", [])
        })

    # 2. Lal Kitab 35-Year Dasha Cycle (३५ वर्षे दशा)
    try:
        y, m, d = map(int, birth_date.split("-"))
        base_date = datetime.date(y, m, d)
    except Exception:
        base_date = datetime.date(1982, 6, 24)

    dasha_cycles = []
    current_start = base_date
    
    # Calculate multiple 35-year cycles across life (e.g. 3 cycles = 105 years)
    for cycle_num in range(3):
        for lord, years in LAL_KITAB_DASHA_ORDER:
            # End date = current_start + years (approximate by year increment)
            try:
                end_date = datetime.date(current_start.year + years, current_start.month, current_start.day)
            except ValueError:
                end_date = datetime.date(current_start.year + years, current_start.month, current_start.day - 1)
            
            # Sub-periods (अन्तरदशा) inside this Lal Kitab Mahadasha
            sub_periods = []
            sub_start = current_start
            for sub_lord, sub_years in LAL_KITAB_DASHA_ORDER:
                # fraction of period
                sub_duration_days = (years * 365.25) * (sub_years / 35.0)
                sub_end = sub_start + datetime.timedelta(days=sub_duration_days)
                sub_periods.append({
                    "lord": sub_lord,
                    "lord_ne": PLANET_NE.get(sub_lord, sub_lord),
                    "start_date": sub_start.strftime("%d/%m/%Y"),
                    "end_date": sub_end.strftime("%d/%m/%Y"),
                })
                sub_start = sub_end
                
            dasha_cycles.append({
                "lord": lord,
                "lord_ne": PLANET_NE.get(lord, lord),
                "years": years,
                "start_date": current_start.strftime("%d/%m/%Y"),
                "end_date": end_date.strftime("%d/%m/%Y"),
                "sub_periods": sub_periods[:3] # sample key sub periods
            })
            current_start = end_date

    return {
        "planet_status": planet_status_rows,
        "dasha_cycles": dasha_cycles,
        "total_dasha_years": 35
    }
